package com.habitloop.app.ui.theme

import androidx.compose.ui.unit.dp

/** Base-8 spacing scale. Never use a dp value outside this set — that's what turned the earlier ad-hoc padding (3/4/6/8/10/12/14/16/18/20/24/28/32dp) into visual noise. */
object Spacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
    val xxl = 48.dp
}
